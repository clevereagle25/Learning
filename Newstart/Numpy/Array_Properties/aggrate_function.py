import numpy as np

arr = np.array([10,20,30,40,50,60])

print(np.sum(arr)) #it will give total of all the values
print(np.min(arr)) #It will give minimun
print(np.max(arr)) #It will give Maximun
print(np.mean(arr)) #It will give mean of all values
print(np.std(arr)) #It will give standard deviation 
print(np.var(arr)) #It will give variance
